import { act, cleanup, renderHook } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { readTimer, useRestTimer } from './useRestTimer'

beforeEach(() => { localStorage.clear(); vi.useFakeTimers(); vi.setSystemTime(1_000_000) })
afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks() })
describe('persistent workout clock', () => {
  it('restores wall-clock rest after unmount/reload and catches up on visibility', () => {
    const first = renderHook(() => useRestTimer(['push:1']))
    act(() => first.result.current.start('push:1', 'bench', 'Bench', 120))
    first.unmount()
    vi.setSystemTime(1_047_400)
    const restored = renderHook(() => useRestTimer(['push:1']))
    expect(restored.result.current.timer?.remaining).toBe(73)
    act(() => { vi.setSystemTime(1_130_000); document.dispatchEvent(new Event('visibilitychange')) })
    expect(restored.result.current.timer?.remaining).toBe(0)
    expect(restored.result.current.timer?.running).toBe(false)
    expect(readTimer()?.notified).toBe(true)
  })
  it('preserves paused time across reload and resumes from the remaining duration', () => {
    const first = renderHook(() => useRestTimer(['push:1']))
    act(() => first.result.current.start('push:1', 'bench', 'Bench', 120))
    act(() => { vi.setSystemTime(1_030_000); first.result.current.toggle() })
    expect(first.result.current.timer?.remaining).toBe(90)
    first.unmount(); vi.setSystemTime(1_500_000)
    const restored = renderHook(() => useRestTimer(['push:1']))
    expect(restored.result.current.timer?.remaining).toBe(90)
    act(() => restored.result.current.toggle())
    expect(restored.result.current.timer?.endAt).toBe(1_590_000)
    act(() => { vi.setSystemTime(1_520_000); restored.result.current.adjust(-15) })
    expect(restored.result.current.timer?.remaining).toBe(55)
    expect(restored.result.current.timer?.endAt).toBe(1_575_000)
  })
  it('keeps a parked workout timer and clears finished/discarded timers', () => {
    const hook = renderHook(({ keys }) => useRestTimer(keys), { initialProps: { keys: ['push:1'] } })
    act(() => hook.result.current.start('push:1', 'bench', 'Bench', 120))
    hook.rerender({ keys: ['pull:2', 'push:1'] })
    expect(hook.result.current.timer?.exerciseId).toBe('bench')
    hook.rerender({ keys: ['pull:2'] })
    expect(hook.result.current.timer).toBeNull()
    expect(readTimer()).toBeNull()
  })
  it('alerts only once even after a reload of an expired timer', () => {
    const vibrate = vi.fn(); Object.defineProperty(navigator, 'vibrate', { configurable: true, value: vibrate })
    localStorage.setItem('optimal-lifts-rest-alerts', 'true')
    const hook = renderHook(() => useRestTimer(['push:1']))
    act(() => hook.result.current.start('push:1', 'bench', 'Bench', 1))
    act(() => vi.advanceTimersByTime(1500))
    expect(vibrate).toHaveBeenCalledTimes(1)
    hook.unmount()
    renderHook(() => useRestTimer(['push:1']))
    expect(vibrate).toHaveBeenCalledTimes(1)
  })
  it('ignores corrupt persisted timers', () => {
    localStorage.setItem('optimal-lifts:rest-timer', '{bad json')
    expect(readTimer()).toBeNull()
    localStorage.setItem('optimal-lifts:rest-timer', JSON.stringify({ id: 'x', workoutKey: 'push:1', running: true, remaining: 20 }))
    expect(readTimer()).toBeNull()
  })
})
